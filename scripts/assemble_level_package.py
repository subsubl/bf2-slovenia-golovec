def safe_hardlink_or_copy(src: str, dst: str):
    """
    Hardlinks src to dst to conserve filesystem space, falling back to copy if needed.
    If dst already exists, checks if it shares the inode; if not, removes and links.
    """
    if os.path.exists(dst):
        try:
            if os.path.samefile(src, dst):
                print(f"Asset already linked: {dst} -> {src}")
                return
        except OSError:
            pass
        os.remove(dst)

    try:
        os.link(src, dst)
        print(f"Hardlinked {src} -> {dst}")
    except OSError:
        shutil.copyfile(src, dst)
        print(f"Copied {src} -> {dst}")


def assemble_package(level_dir: str = DEFAULT_LEVEL_DIR, root_dir: str = ROOT_DIR):
    """Assembles all required level package components into level_dir."""
    print("=" * 80)
    print("BATTLEFIELD 2 LEVEL PACKAGE ASSEMBLER")
    print(f"Target Level Directory: {level_dir}")
    print(f"Source Root Directory:  {root_dir}")
    print("=" * 80)

    os.makedirs(level_dir, exist_ok=True)
    os.makedirs(os.path.join(level_dir, "Overgrowth"), exist_ok=True)

    # 1. Hardlink large binary terrain assets (0 extra disk allocation)
    src_heightmap = os.path.join(root_dir, "Heightmap.raw")
    dst_heightmap = os.path.join(level_dir, "Heightmap.raw")
    if os.path.isfile(src_heightmap):
        safe_hardlink_or_copy(src_heightmap, dst_heightmap)
    else:
        print(f"WARNING: Source heightmap not found at {src_heightmap}")

    src_colormap = os.path.join(root_dir, "ColorMap.dds")
    dst_colormap = os.path.join(level_dir, "ColorMap.dds")
    if os.path.isfile(src_colormap):
        safe_hardlink_or_copy(src_colormap, dst_colormap)
    else:
        print(f"WARNING: Source colormap not found at {src_colormap}")

    # 2. Copy Heightdata.con and Terrain.con
    src_heightdata = os.path.join(root_dir, "Heightdata.con")
    dst_heightdata = os.path.join(level_dir, "Heightdata.con")
    shutil.copyfile(src_heightdata, dst_heightdata)
    print(f"Copied Heightdata.con -> {dst_heightdata}")

    src_terrain = os.path.join(root_dir, "Terrain.con")
    dst_terrain = os.path.join(level_dir, "Terrain.con")
    shutil.copyfile(src_terrain, dst_terrain)
    print(f"Copied Terrain.con -> {dst_terrain}")

    # 3. Write init.con, Sky.con, Water.con, GameplayObjects.con
    init_path = os.path.join(level_dir, "init.con")
    with open(init_path, "w", encoding="utf-8") as f:
        f.write(INIT_CON_CONTENT)
    print(f"Written init.con -> {init_path}")

    sky_path = os.path.join(level_dir, "Sky.con")
    with open(sky_path, "w", encoding="utf-8") as f:
        f.write(SKY_CON_CONTENT)
    print(f"Written Sky.con -> {sky_path}")

    water_path = os.path.join(level_dir, "Water.con")
    with open(water_path, "w", encoding="utf-8") as f:
        f.write(WATER_CON_CONTENT)
    print(f"Written Water.con -> {water_path}")

    gameplay_path = os.path.join(level_dir, "GameplayObjects.con")
    with open(gameplay_path, "w", encoding="utf-8") as f:
        f.write(GAMEPLAY_OBJECTS_CON_CONTENT)
    print(f"Written GameplayObjects.con -> {gameplay_path}")

    # 4. Verify integrity of pre-existing M1 & M2 artifacts
    static_objs_path = os.path.join(level_dir, "StaticObjects.con")
    overgrowth_sys_path = os.path.join(level_dir, "OvergrowthSystem.con")
    overgrowth_raw_path = os.path.join(level_dir, "Overgrowth", "Overgrowth.raw")

    assert os.path.isfile(static_objs_path), f"M1 artifact missing: {static_objs_path}"
    assert os.path.getsize(static_objs_path) > 100000, f"M1 StaticObjects.con size abnormal: {os.path.getsize(static_objs_path)}"

    assert os.path.isfile(overgrowth_sys_path), f"M2 artifact missing: {overgrowth_sys_path}"
    assert os.path.getsize(overgrowth_sys_path) > 1000, f"M2 OvergrowthSystem.con size abnormal: {os.path.getsize(overgrowth_sys_path)}"

    assert os.path.isfile(overgrowth_raw_path), f"M2 artifact missing: {overgrowth_raw_path}"
    assert os.path.getsize(overgrowth_raw_path) == 4198401, f"M2 Overgrowth.raw size abnormal: {os.path.getsize(overgrowth_raw_path)}"

    print("Verified pre-existing M1 and M2 artifacts (all intact and non-empty).")
    print("Level package assembly completed successfully.")


def main():
    parser = argparse.ArgumentParser(description="Battlefield 2 Level Package Assembler")
    parser.add_argument("--level-dir", default=DEFAULT_LEVEL_DIR, help="Target level package directory")
    parser.add_argument("--root-dir", default=ROOT_DIR, help="Source root directory containing raw assets")
    args = parser.parse_args()

    assemble_package(level_dir=args.level_dir, root_dir=args.root_dir)


if __name__ == "__main__":
    main()
